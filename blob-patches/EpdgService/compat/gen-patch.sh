#!/bin/bash
# Regenerate ../0001-EpdgService-Add-the-compat-classes.patch from src/.
# Usage: gen-patch.sh <android source root with a built framework>
set -e
TOP=$(realpath "$1"); HERE=$(dirname "$(realpath "$0")")
JDK=$TOP/prebuilts/jdk/jdk21/linux-x86/bin
IM=$TOP/out/soong/.intermediates
CP=$IM/frameworks/base/framework/android_common/turbine-combined/framework.jar
CP=$CP:$IM/frameworks/opt/telephony/telephony-common/android_common/turbine-combined/telephony-common.jar
for m in framework-wifi framework-connectivity; do
    CP=$CP:$(find $IM/packages/modules -path "*/$m.impl/android_common*/turbine-combined/$m.jar" | head -1)
done
TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT
mkdir "$TMP/classes"
"$JDK/javac" --release 8 -nowarn -encoding UTF-8 -cp "$CP" \
    -d "$TMP/classes" $(find "$HERE/src" -name '*.java')
"$JDK/java" -cp "$TOP/prebuilts/r8/r8.jar" com.android.tools.r8.D8 --release --min-api 31 \
    --lib "$TOP/prebuilts/sdk/31/system/android.jar" \
    --output "$TMP" $(find "$TMP/classes" -name '*.class')
# Disassemble with the apktool extract-utils uses; the classes become the
# APK's second dex.
(cd "$TMP" && zip -q compat.jar classes.dex)
"$JDK/java" -jar "$TOP/prebuilts/extract-tools/common/apktool/apktool.jar" \
    d -f -r -o "$TMP/out" "$TMP/compat.jar" >/dev/null
mkdir "$TMP/repo"; mv "$TMP/out/smali" "$TMP/repo/smali_classes2"
cd "$TMP/repo"
git init -q; git add -A
GIT_AUTHOR_DATE="2026-10-07T00:00:00+0700" git -c user.name=thongass000 \
    -c user.email=tienthong2004@gmail.com commit -q -F - << 'MSG'
EpdgService: Add the compat classes

Generated by compat/gen-patch.sh from compat/src.

EpdgService was built against Samsung's framework. Add the Samsung
classes it uses (SemSystemProperties, SemFloatingFeature, SemCscFeature,
SemHqmManager), Android 10's Inet4AddressUtils, EpdgCompat, which stands
in for the framework methods Android 12 and later lack, and WfcSync,
which copies the framework's Wi-Fi Calling switch and mode into
EpdgService's provider.

Assisted-by: LLM
MSG
git format-patch -q -1 --root --no-signature --zero-commit --stdout \
    > "$HERE/../0001-EpdgService-Add-the-compat-classes.patch"
