#!/bin/bash
# Regenerate ../0012-imsservice-Add-the-SMS-bridge-classes.patch from src/.
# Usage: gen-patch.sh <android source root with a built framework>
set -e
TOP=$(realpath "$1"); HERE=$(dirname "$(realpath "$0")")
JDK=$TOP/prebuilts/jdk/jdk21/linux-x86/bin
IM=$TOP/out/soong/.intermediates
CP=$IM/frameworks/base/framework/android_common/turbine-combined/framework.jar
CP=$CP:$IM/frameworks/opt/telephony/telephony-common/android_common/turbine-combined/telephony-common.jar
CP=$CP:$IM/frameworks/opt/net/ims/ims-common/android_common/turbine-combined/ims-common.jar
TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT
mkdir "$TMP/classes"
"$JDK/javac" --release 8 -nowarn -encoding UTF-8 -cp "$CP" \
    -d "$TMP/classes" $(find "$HERE/src" "$HERE/stubs" -name '*.java')
# Only the bridge goes into the dex; the stubs stand in for classes already
# in imsservice.apk.
rm -rf "$TMP/classes/com/google" "$TMP/classes/com/sec/ims" \
    "$TMP/classes/com/sec/internal/google/ImsMmtelFeature.class"
"$JDK/java" -cp "$TOP/prebuilts/r8/r8.jar" com.android.tools.r8.D8 --release --min-api 31 \
    --lib "$TOP/prebuilts/sdk/31/system/android.jar" \
    --output "$TMP" $(find "$TMP/classes" -name '*.class')
# Disassemble with the apktool extract-utils uses; the classes become the
# APK's second dex.
(cd "$TMP" && zip -q bridge.jar classes.dex)
"$JDK/java" -jar "$TOP/prebuilts/extract-tools/common/apktool/apktool.jar" \
    d -f -r -o "$TMP/out" "$TMP/bridge.jar" >/dev/null
mkdir "$TMP/repo"; mv "$TMP/out/smali" "$TMP/repo/smali_classes2"
cd "$TMP/repo"
git init -q; git add -A
GIT_AUTHOR_DATE="2026-10-06T15:00:06+0700" git -c user.name=thongass000 \
    -c user.email=tienthong2004@gmail.com commit -q -F - << 'MSG'
imsservice: Add the SMS bridge classes

Generated by bridge/gen-patch.sh from bridge/src.

Samsung's GoogleImsServiceAdapter is a compat ImsService; Android 12
wraps it in MmTelFeatureCompatAdapter, which has no SMS, and the SMS
methods of Samsung's GoogleImsService are not part of AOSP's IImsService.
Add an Android 12 ImsService that wraps the compat feature in-process
and adds an ImsSmsImplBase backed by GoogleImsService (the new
GoogleImsServiceAdapter), SmsListenerCompat for the Android 10
IImsSmsListener calls of ImsSmsImpl and SmsServiceModule's
onReceiveSMSAck, which turns an RP-ERROR into a failed send,
TelephonyCompat for the Samsung and Android 10 framework methods
ImsSmsImpl uses, and the Samsung TelephonyFeatures and SemCscFeature
classes it needs.

GoogleImsService keeps one registration listener per session, so the
feature registers a single listener that hands the registration events
on to the ImsRegistrationCompatAdapter and the capability changes (VoLTE,
video, Ut) to Android; with both added, the adapter's replaced the
feature's and Android never saw Ut, sending call settings over CS.

Assisted-by: LLM
MSG
git format-patch -q -1 --root --no-signature --zero-commit --stdout \
    > "$HERE/../0012-imsservice-Add-the-SMS-bridge-classes.patch"
